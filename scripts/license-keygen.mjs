#!/usr/bin/env node
// Creates the signing key pair for license codes. The private key stays in ~/.inkmap (never in the
// repository); the public key is written into packages/core/src/license-key.ts.
import { existsSync } from "node:fs";
import { chmod, mkdir, writeFile } from "node:fs/promises";
import { homedir } from "node:os";
import { join } from "node:path";
import { generateLicenseKeys } from "../packages/core/src/license.ts";

const dir = process.env.INKMAP_KEY_DIR ?? join(homedir(), ".inkmap");
const privatePath = join(dir, "license-private.key");
if (existsSync(privatePath) && !process.argv.includes("--force")) {
  console.error(`已存在私钥：${privatePath}\n重新生成会让已售出的激活码全部失效。确需重新生成请加 --force。`);
  process.exit(1);
}

const { publicKey, privateKey } = await generateLicenseKeys();
await mkdir(dir, { recursive: true, mode: 0o700 });
await writeFile(privatePath, privateKey + "\n", { mode: 0o600 });
await chmod(privatePath, 0o600);
await writeFile(
  new URL("../packages/core/src/license-key.ts", import.meta.url),
  `// Public half of the license signing key; generated by scripts/license-keygen.mjs.\nexport const LICENSE_PUBLIC_KEY = "${publicKey}";\n\n/** Ids of leaked or refunded codes. */\nexport const REVOKED_LICENSES: readonly string[] = [];\n`,
);
console.log(`私钥：${privatePath}（请备份到安全的地方，丢失后无法再发码）`);
console.log(`公钥已写入 packages/core/src/license-key.ts`);
